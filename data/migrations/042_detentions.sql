-- Detention module — Art's sheet model (OpenRoad email → claim tracking).
CREATE TABLE IF NOT EXISTS detentions (
  id VARCHAR(64) PRIMARY KEY,
  customer VARCHAR(255) NULL,
  customer_email VARCHAR(255) NULL,
  dispatcher VARCHAR(128) NULL,
  load_number VARCHAR(64) NULL,
  shipment_number VARCHAR(64) NULL,
  driver_name VARCHAR(255) NULL,
  driver_number VARCHAR(64) NULL,
  truck_number VARCHAR(64) NULL,
  stop_type VARCHAR(32) NULL,
  pu_location TEXT NULL,
  pu_appt VARCHAR(128) NULL,
  del_location TEXT NULL,
  del_appt VARCHAR(128) NULL,
  arrival_time VARCHAR(128) NULL,
  detention_start VARCHAR(128) NULL,
  driver_departure VARCHAR(128) NULL,
  detention_mins INT NULL,
  detention_time_label VARCHAR(64) NULL,
  rate_per_hour DECIMAL(10,2) NOT NULL DEFAULT 25.00,
  amount DECIMAL(12,2) NULL,
  billable_amount DECIMAL(12,2) NULL,
  settled_amount DECIMAL(12,2) NULL,
  status VARCHAR(64) NOT NULL DEFAULT 'New',
  awaiting_us TINYINT(1) NOT NULL DEFAULT 1,
  follow_up_date DATE NULL,
  load_link TEXT NULL,
  thread_url TEXT NULL,
  message_id VARCHAR(255) NULL,
  thread_id VARCHAR(255) NULL,
  calendar_event_id VARCHAR(255) NULL,
  email_date DATETIME(3) NULL,
  last_reply_from VARCHAR(255) NULL,
  last_reply_at DATETIME(3) NULL,
  history_json JSON NULL,
  source VARCHAR(64) NOT NULL DEFAULT 'import',
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  INDEX idx_detentions_status (status),
  INDEX idx_detentions_dispatcher (dispatcher),
  INDEX idx_detentions_follow_up (follow_up_date),
  INDEX idx_detentions_load (load_number),
  INDEX idx_detentions_shipment (shipment_number),
  INDEX idx_detentions_updated (updated_at)
);

CREATE TABLE IF NOT EXISTS detention_notes (
  id INT PRIMARY KEY AUTO_INCREMENT,
  detention_id VARCHAR(64) NOT NULL,
  author VARCHAR(255) NULL,
  body TEXT NOT NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  INDEX idx_detention_notes_detention (detention_id),
  CONSTRAINT fk_detention_notes_detention
    FOREIGN KEY (detention_id) REFERENCES detentions(id) ON DELETE CASCADE
);
